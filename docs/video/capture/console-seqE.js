const { ouvrir } = require('./pw.js');
const D = '/tmp/saife-video-v1/rec/console/';
const fs = require('fs');
(async () => {
  const { ctx, page } = await ouvrir();
  await ctx.addInitScript(() => { try { localStorage.setItem('dedale.analyste', 'Marc N.'); } catch (e) {} });
  await page.goto('http://localhost:5190/?incident=INC-0003', { waitUntil: 'networkidle' });
  await page.waitForTimeout(3000);
  await page.getByRole('button', { name: /Exporter/ }).click();
  await page.waitForTimeout(600);
  const [rapport] = await Promise.all([ctx.waitForEvent('page'), page.getByRole('menuitem', { name: /Rapport/ }).click()]);
  await rapport.setViewportSize({ width: 1600, height: 900 });
  await rapport.waitForLoadState('networkidle');
  await rapport.waitForTimeout(1500);
  await rapport.screenshot({ path: D + 'd02-rapport-haut.png' });
  const h = await rapport.evaluate(() => document.documentElement.scrollHeight);
  await rapport.evaluate((y) => window.scrollTo(0, y), 640); await rapport.waitForTimeout(400);
  await rapport.screenshot({ path: D + 'd03-rapport-milieu.png' });
  await rapport.evaluate((y) => window.scrollTo(0, y), h); await rapport.waitForTimeout(400);
  await rapport.screenshot({ path: D + 'd04-rapport-bas.png' });
  fs.writeFileSync(D + 'rapport-INC-0003.html', await rapport.content());
  await rapport.close();
  await page.bringToFront();
  await page.getByRole('button', { name: /Exporter/ }).click();
  await page.waitForTimeout(600);
  await page.getByRole('menuitem', { name: /Alertes et SMS/ }).click();
  await page.waitForTimeout(1500);
  await page.screenshot({ path: D + 'e02-alertes-et-sms.png' });
  const ecs = await page.evaluate(async () => { const r = await fetch('/api/incidents/INC-0003/export?format=ecs'); return r.ok ? JSON.stringify(await r.json(), null, 2) : 'HTTP ' + r.status; });
  fs.writeFileSync(D + 'INC-0003-ecs.json', ecs);
  const sigma = await page.evaluate(async () => { const r = await fetch('/api/incidents/INC-0003/export?format=sigma'); return r.ok ? await r.text() : 'HTTP ' + r.status; });
  fs.writeFileSync(D + 'INC-0003-sigma.yml', sigma);
  console.log('hauteur rapport', h, 'ecs', ecs.length, 'sigma', sigma.length);
  await ctx.close();
})().catch(e => { console.error(e); process.exit(1); });
